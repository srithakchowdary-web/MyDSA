class Solution {
public:
    long long countCommas(long long n) {
        if(n < 1000) return 0;
        int digits = 0;
        long long val = n;
        while(val > 0){
            val /= 10;
            ++digits;
        }
        long long ans;
        //totla no.of commas used 
        if(digits == 5)  ans = 9000*1+(n-9999)*1;
        if(digits == 6)  ans = 9000*1+90000*1+(n-99999)*1;
        if(digits == 7)  ans = 9000*1+90000*1+900000*1+(n-999999)*2;
        if(digits == 8)  ans = 9000*1+90000*1+900000*1+9000000*2+(n-9999999)*2;
        if(digits == 9)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+(n-99999999)*2;
        if(digits == 10)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+(n-999999999)*3;
        if(digits == 11)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+9000000000LL*3+(n-9999999999LL)*3;
        if(digits == 12)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+9000000000LL*3+90000000000LL*3+(n-99999999999LL)*3;
        if(digits == 13)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+9000000000LL*3+90000000000LL*3+900000000000LL*3+(n-999999999999LL)*4;
        if(digits == 14)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+9000000000LL*3+90000000000LL*3+900000000000LL*3+9000000000000LL*4+(n-9999999999999LL)*4;
        if(digits == 15)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+9000000000LL*3+90000000000LL*3+900000000000LL*3+9000000000000LL*4+90000000000000LL*4+(n-99999999999999LL)*4;
        if(digits == 16)  ans = 9000*1+90000*1+900000*1+9000000*2+90000000*2+900000000*2+9000000000LL*3+90000000000LL*3+900000000000LL*3+9000000000000LL*4+90000000000000LL*4+900000000000000LL*4+(n-999999999999999LL)*5;
        return ans;
    }
};